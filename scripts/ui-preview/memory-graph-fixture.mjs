/** memory_entries 的桩:按 scope 返回活动条目(归档条目只有 memory_entry_get 取得到)。 */
export function memoryEntriesFor(scope) {
  return MEMORY_ENTRIES_FIXTURE.filter((entry) => entry.scope === scope && !entry.archived);
}

/** memory_entry_get 的桩:活动或归档都取得到。 */
export function memoryEntryFor(scope, id) {
  return MEMORY_ENTRIES_FIXTURE.find((entry) => entry.scope === scope && entry.id === id) ?? null;
}
