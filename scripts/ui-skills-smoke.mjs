/* Production UI and disposable IPC fixtures. Native behavior has a separate check. */
/* global window, document */
import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
import { chromium } from "playwright-core";
import { startPreviewServer } from "./ui-preview/server.mjs";

const output = "output/playwright/skills";
await mkdir(output, { recursive: true });
const server = await startPreviewServer({ port: 0 });
const browser = await chromium.launch({ channel: "msedge", headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const checks = [], errors = [];
const check = (value, label) => { assert(value, label); checks.push(label); console.log(`PASS ${label}`); };
const settle = () => page.evaluate(() => window.__kzPreview.settle());
page.setDefaultTimeout(12000);
page.on("pageerror", error => errors.push(error.message));
try {
  await page.goto(`${server.origin}/?scene=chat&theme=light`);
  await page.waitForFunction(() => window.__kzPreview?.ready); await settle();
  check(await page.locator("#rail-sidebar-toggle").evaluate(el => el.nextElementSibling.id === "skills-nav"), "Skills sits directly below the sidebar toggle");
  check(!await page.locator("#skills-picker, #skills-menu").count(), "The conversation has no Skills picker or management menu");
  await page.locator("#skills-nav").click(); await settle();
  await page.waitForFunction(() => document.querySelectorAll(".skill-library-row").length === 9);
  check(await page.locator("body").getAttribute("data-app-scope") === "global", "Skills opens as a global view without changing the execution project");
  check(await page.locator(".skill-library-row").count() === 9, "Nine built-in skills are available");
  const pdf = page.locator('[data-skill-name="pdf"]');
  await pdf.getByRole("switch").uncheck({ force: true }); await settle();
  check(!await pdf.getByRole("switch").isChecked(), "Disabling a skill persists in the global library");
  await page.evaluate(async () => {
    const sessions = await import("/09-sessions.js"), shell = await import("/03-shell.js");
    const f = await window.__kzPreview.fixtures();
    for (const item of f.state.processes) item.running = false;
    const peer = f.state.processes.find(item => item.id !== shell.activeProcessId);
    await sessions.switchProcess(peer.id); shell.navigate_view("skills");
  }); await settle(); await page.waitForFunction(() => document.body.dataset.view === "skills");
  check(!await pdf.getByRole("switch").isChecked(), "Changing conversations retains the same global enable state");
  await page.evaluate(() => window.__kzPreview.setCommand("skills_set_enabled", () => { throw "fixture save failed"; }));
  await pdf.getByRole("switch").check({ force: true }); await settle();
  check(!await pdf.getByRole("switch").isChecked() && (await page.locator("#skills-status").innerText()).includes("failed"), "A failed toggle leaves the previous state visible");
  await pdf.locator(".skill-library-details").click(); await settle();
  check(await page.locator("#skill-instructions").getAttribute("readonly") !== null && !await page.locator("#skills-delete").isVisible(), "Built-ins can be inspected without being overwritten or deleted");
  await page.locator("#skills-copy").click(); await settle();
  check(await page.locator("#skill-name").inputValue() === "pdf-custom" && await page.locator("#skills-save").isVisible(), "A built-in can be copied to an editable personal skill");
  await page.locator("#skills-editor-close").click();
  await page.locator("#skills-generate-open").click();
  await page.locator("#skills-generation-prompt").fill("按照我的周报模板整理工作进展和下周计划");
  const before = await page.evaluate(() => window.__kzPreview.calls.filter(call => call.cmd === "run_prompt").length);
  await page.locator("#skills-generate").click(); await settle();
  check(await page.locator("#skill-name").inputValue() === "weekly-review", "AI generation fills an editable draft in the Skills module");
  check(await page.evaluate(before => window.__kzPreview.calls.filter(call => call.cmd === "run_prompt").length === before, before), "Generating a skill does not submit a main conversation message");
  await page.locator("#skills-save").click(); await settle();
  check(await page.locator('[data-skill-name="weekly-review"]').count() === 1, "Saving a draft adds a personal skill to the global library");
  await page.screenshot({ path: `${output}/skills-editor-light.png` });
  await page.locator("#skill-instructions").fill("Updated draft survives a failed save");
  await page.evaluate(() => window.__kzPreview.setCommand("skills_save", () => { throw "fixture stale revision"; }));
  await page.locator("#skills-save").click(); await settle();
  check((await page.locator("#skills-editor-error").innerText()).includes("stale") && (await page.locator("#skill-instructions").inputValue()).includes("survives"), "A failed edit retains its draft and reports the error");
  await page.locator("#skill-instructions").fill("读取用户提供的周报模板，保留原有结构，根据实际资料整理进展，不编造数据。");
  await page.locator("#skills-editor-close").click();
  await page.locator('[data-skill-filter="builtin"]').click();
  check(await page.locator(".skill-library-row").count() === 9, "Source filters keep built-in and personal skills distinct");
  await page.locator("#skills-search").fill("code-review");
  check(await page.locator(".skill-library-row").count() === 1, "Search matches the invocation name");
  await page.locator("#skills-search").fill("");
  await page.screenshot({ path: `${output}/skills-library-light.png` });
  await page.setViewportSize({ width: 760, height: 900 });
  await page.screenshot({ path: `${output}/skills-library-narrow.png` });
  check(await page.locator("#view-skills").evaluate(el => el.scrollWidth <= el.clientWidth + 1), "The Skills page fits the narrow viewport");
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`${server.origin}/?scene=empty&theme=dark&lang=en`);
  await page.waitForFunction(() => window.__kzPreview?.ready); await settle();
  await page.locator("#skills-nav").click(); await settle();
  await page.waitForFunction(() => document.querySelectorAll(".skill-library-row").length === 9);
  check(await page.locator("#skills-create").innerText() === "Create Skill", "The global module works without a project and translates to English");
  await page.screenshot({ path: `${output}/skills-library-dark.png` });
  check(errors.length === 0, `No browser runtime errors: ${errors.join("; ")}`);
  await writeFile(`${output}/checks.json`, JSON.stringify({ checks, errors }, null, 2));
} finally { await browser.close(); await new Promise(resolve => server.server.close(resolve)); }
