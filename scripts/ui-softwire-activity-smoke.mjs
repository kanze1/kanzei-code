// Real CSS and production UI, controlled backend events; never starts a model.
/* global window, document, getComputedStyle */
import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { chromium } from "playwright-core";
import { startPreviewServer } from "./ui-preview/server.mjs";

const output = path.resolve("output/playwright/softwire/activity");
await mkdir(output, { recursive: true });
const server = await startPreviewServer({ port: 0 });
const browser = await chromium.launch({ channel: "msedge", headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 },
  ...(process.argv.includes("--no-video") ? {} : { recordVideo: { dir: output, size: { width: 1440, height: 900 } } }) });
page.setDefaultTimeout(9000);
const checks = [], errors = [];
const check = (value, label) => { assert(value, label); checks.push(label); };
page.on("pageerror", error => errors.push(error.message));
const settle = () => page.evaluate(() => window.__kzPreview.settle());
const module = name => page.locator(`[data-module="${name}"]`);
const still = name => module(name).evaluate(el => el.getAnimations({subtree:true}).every(a => a.playState !== "running" || a.effect.getTiming().iterations !== Infinity));
// 主对话的状态不再有自己的圆形节点:状态与动效都落在概览页头的运行状态(#sw-runtime)上,六行基线只表达各模块的真实活动。
const runtime = page.locator("#sw-runtime");
const stillRuntime = () => runtime.evaluate(el => el.getAnimations({subtree:true}).every(a => a.playState !== "running" || a.effect.getTiming().iterations !== Infinity));
const waveRuns = name => module(name).locator(".sw-wave").evaluate(el => getComputedStyle(el,"::after").animationName === "sw-wave-run");
let id;
const phase = async state => { await page.evaluate(async ({session,state}) => (await import("/03-shell.js")).transitionSession(session,state), {session:id.session,state}); await settle(); };
const emit = async (name, payload = {}) => { await page.evaluate(({name,payload}) => window.__kzPreview.emit(name,payload),{name,payload:{sessionId:id.session,...payload}}); await settle(); };
const refresh = async () => { await page.locator("#sw-refresh").click(); await settle(); };
const shot = async name => { await page.mouse.move(2,2); await page.waitForTimeout(300); await page.screenshot({path:path.join(output,`${name}.png`)}); };
try {
  await page.goto(`${server.origin}/?scene=startup&theme=dark`);
  await page.waitForFunction(() => window.__kzPreview?.ready);
  id = await page.evaluate(async () => {
    const f = await window.__kzPreview.fixtures();
    f.state.processes.forEach(line => {line.running=false;line.stage="空闲";});
    const snapshot = f.commands.workspace_snapshot();
    snapshot.projects.forEach(p => p.lines.forEach(line => {line.running=false;line.stage="空闲";}));
    const a=snapshot.projects[0];
    window.__activity={f,snapshot,questions:[]};
    window.__kzPreview.setCommand("workspace_snapshot",()=>structuredClone(snapshot));
    window.__kzPreview.setCommand("softwire_questions",()=>structuredClone(window.__activity.questions));
    const shell=await import("/03-shell.js");
    for (const p of snapshot.projects) for (const line of p.lines) shell.transitionSession(line.session_id,"idle");
    return {project:a.path,session:a.lines[0].session_id,other:a.lines[1].session_id};
  });
  await page.locator('.workbench-project-link.active').click(); await page.locator('[data-work-surface="project"]').click(); await page.locator('#sw-refresh').click(); await settle();
  const project = page.locator(`.workbench-project-link[data-path="${id.project}"]`);
  await phase("idle");
  check(await stillRuntime() && await runtime.getAttribute("data-state")==="idle","An idle project has no execution animation");
  await shot("idle-dark");
  for (const theme of ["dark","light"]) {
    await page.evaluate(theme=>document.documentElement.setAttribute("data-theme",theme),theme);
    await phase("starting");
    check(await runtime.getAttribute("data-state")==="starting" && await project.getAttribute("data-activity")==="starting",`${theme}: launch appears immediately without waiting for model output or polling`);
    check(await project.evaluate(el=>getComputedStyle(el,"::after").content==="none" && el.getAnimations({subtree:true}).filter(a=>a.effect.getTiming().iterations===Infinity).length===1),`${theme}: exactly one sidebar spinner, no generic duplicate`);
    check(await runtime.evaluate(el=>getComputedStyle(el,"::before").animationName==="sw-spin"),`${theme}: launch rotates the header mark instead of showing a running wave`);
    await shot(`starting-${theme}`);
    await emit("kz:turn",{turn:1}); await emit("kz:status",{stage:"执行"});
    await emit("kz:tool-start",{id:`read-${theme}`,name:"read",input:{path:"README.md"}});
    check(await waveRuns("work") && await waveRuns("tools") && !await waveRuns("memory"),`${theme}: the running requirement and the pending tool wave in orange while memory stays a straight line`);
    check(await still("memory") && await still("history"),`${theme}: unrelated modules remain still`);
    check(await waveRuns("batch") && await module("batch").getAttribute("data-state")==="working",`${theme}: a running line in the verifying phase lights the verification baseline`);
    check(await module("tools").locator(".sw-wave").evaluate(el=>el.getAnimations().some(a=>a.playState==="running")),`${theme}: a real tool event kicks the baseline once (finite)`);
    await shot(`working-${theme}`);
    await page.waitForTimeout(1100);
    await refresh();
    check(await module("tools").locator(".sw-wave").evaluate(el=>el.getAnimations().length===0 && getComputedStyle(el,"::before").borderTopStyle==="solid"),`${theme}: long-running tool keeps a solid baseline; refresh never restarts the kick`);
    await emit("kz:tool-end",{id:`read-${theme}`,name:"read",ok:true});
    check(await still("tools") && (await module("tools").innerText()).includes("最近调用完成"),`${theme}: completed call retains its result and stops moving`);
    await phase("stopping");
    check(await runtime.getAttribute("data-state")==="stopping" && await project.getAttribute("data-activity")==="stopping" && await stillRuntime(),`${theme}: stopping keeps the pending control intent without a running breath`);
    await shot(`stopping-${theme}`);
    await emit("kz:stopped");
    check(await runtime.getAttribute("data-state")==="stopped" && await stillRuntime(),`${theme}: stop confirmation settles the node`);
  }
  await phase("auto_pending");
  check(await runtime.getAttribute("data-state")==="waiting" && await stillRuntime() && await project.getAttribute("data-activity")==="waiting","Automatic next-round wait has a static pause mark");
  await shot("waiting-light");
  await phase("failed");
  check(await runtime.getAttribute("data-state")==="failed" && await runtime.getAttribute("data-symbol")==="!" && await stillRuntime(),"Failure has a static error mark, not a spinner");
  await shot("failed-light");
  await emit("kz:turn",{turn:2}); await emit("kz:status",{stage:"执行"});
  await emit("kz:tool-start",{id:"long",name:"bash"});
  await emit("kz:tool-start",{id:"short",name:"read"});
  await emit("kz:tool-end",{id:"short",name:"read",ok:true});
  check(await module("tools").getAttribute("data-state")==="working" && (await module("tools").innerText()).includes("bash"),"Finishing a newer call does not hide an older call still running");
  await emit("kz:tool-end",{id:"long",name:"bash",ok:false});
  check(await module("tools").getAttribute("data-state")==="result" && await runtime.getAttribute("data-state")==="running" && await still("tools"),"A failed tool result remains visible without declaring the agent failed");
  await emit("kz:tool-start",{id:"recall",name:"memory_recall"});
  check(await module("memory").getAttribute("data-state")==="reading","Recall activates only the memory being accessed");
  await shot("memory-read-light");
  await emit("kz:tool-end",{id:"recall",name:"memory_recall",ok:true});
  await emit("kz:tool-start",{id:"write",name:"memory",input:{action:"add"}});
  check(await module("memory").getAttribute("data-state")==="writing","Memory write has its own direction and state");
  await emit("kz:tool-end",{id:"write",name:"memory",ok:true});
  await emit("kz:status",{stage:"压缩"});
  check(await module("history").getAttribute("data-state")==="working","Compaction has a separate active operation");
  await emit("kz:compacted",{summary:"本轮压缩完成"});
  check(await module("history").getAttribute("data-state")==="idle" && await still("history"),"Compaction completion ends motion without waiting for a new stage label");
  await emit("kz:status",{stage:"执行"});
  await emit("kz:compacted",{sessionId:id.other,summary:"另一会话压缩完成"});
  await module("history").click(); await settle();
  await page.getByRole("button",{name:"最近压缩记录  ›",exact:true}).click(); await settle();
  check((await page.locator(".sw-evidence").innerText()).includes("本轮压缩完成") && !(await page.locator(".sw-evidence").innerText()).includes("另一会话"),"Compaction evidence remains scoped to its session");
  await page.locator('[data-work-surface="project"]').click(); await settle();
  await page.evaluate(id=>{window.__activity.questions=[{projectDir:id.project,sessionId:id.other,id:42,revision:"1",question:"另一条线路的问题"}];},id); await refresh();
  check(await runtime.getAttribute("data-state")==="running" && !await page.locator(".sw-attention").isVisible(),"Another session's question never puts the selected agent into waiting");
  await page.evaluate(id=>{window.__activity.questions[0].sessionId=id.session;},id); await refresh();
  check(await page.getByRole("heading",{name:"回复提问",exact:true}).isVisible() && (await page.locator(".sw-question").innerText())==="另一条线路的问题"
    && await page.locator("#prompt").isVisible(),"A foreground question for the selected session automatically opens its reply detail");
  await page.locator(".sw-detail-head .sw-back").click(); await settle();
  check(await runtime.getAttribute("data-state")==="attention" && await stillRuntime() && await page.locator(".sw-attention").isVisible(),"A question for this session replaces breathing with a reply marker");
  await shot("attention-light");
  await page.evaluate(()=>{window.__activity.questions=[];}); await refresh();
  await emit("kz:tool-start",{id:"child",name:"task",input:{description:"检查状态边界",prompt:"检查状态边界"}});
  await emit("kz:task-progress",{id:"child",text:"",trace:{child_id:"child-1",phase:"start",name:"read",input:{path:"README.md"}}});
  check(await module("tools").getAttribute("data-state")==="waiting" && (await module("tools").innerText()).includes("等待子任务") && await module("tasks").getAttribute("data-state")==="running" && await project.getAttribute("data-activity")==="running","The parent's task call waits (dashed) while the child works and the project remains active");
  await shot("subagent-light");
  await emit("kz:tool-end",{id:"child",name:"task",ok:true});
  await emit("kz:tool-start",{id:"interrupted",name:"read"});
  await emit("kz:idle");
  check(await still("tools") && await module("tools").getAttribute("data-state")==="stopped","Terminal events settle a call even if its result was never received");
  await emit("kz:turn",{turn:3});
  check(await still("tools"),"A new round never reactivates an unfinished historical call");
  await page.emulateMedia({reducedMotion:"reduce"});
  await emit("kz:tool-start",{id:"reduced",name:"read"});
  check(await stillRuntime() && await still("tools") && await still("work") && await module("tools").locator(".sw-wave").evaluate(el=>el.getAnimations().length===0),"Reduced motion removes all continuous and event animations while retaining state");
  check(await page.evaluate(()=>window.__kzPreview.calls.every(c=>c.cmd!=="run_prompt")),"Observation never sends a model request");
  await page.emulateMedia({reducedMotion:"no-preference"}); await phase("idle");
  await page.evaluate(()=>window.__kzPreview.setCommand("run_prompt",()=>new Promise(resolve=>{window.__activity.releaseRun=resolve;})));
  await page.locator("#prompt").fill("仅通过隔离 IPC 检查启动反馈"); await page.locator("#send").click();
  await page.waitForFunction(()=>Boolean(window.__activity.releaseRun));
  await page.locator('[data-work-surface="project"]').click();
  check(await runtime.getAttribute("data-state")==="starting" && await project.getAttribute("data-activity")==="starting","An actual send click shows starting while the launch acknowledgement is pending");
  await page.evaluate(async()=>{await (await import("/09-sessions.js")).refreshProcesses();});
  check(await project.getAttribute("data-activity")==="starting","An idle process poll cannot turn a pending launch into running");
  await page.evaluate(()=>window.__activity.releaseRun(null)); await settle();
  check(await runtime.getAttribute("data-state")==="running","Launch acknowledgement advances the operation without requiring a first token");
  await page.evaluate(()=>window.__kzPreview.setCommand("stop_run",()=>new Promise((resolve,reject)=>{window.__activity.releaseStop=resolve;window.__activity.rejectStop=reject;})));
  await page.locator(".sw-stop").click(); await page.waitForFunction(()=>Boolean(window.__activity.releaseStop));
  check(await runtime.getAttribute("data-state")==="stopping" && await stillRuntime(),"An actual stop click immediately presents stopping");
  await page.evaluate(()=>window.__activity.rejectStop("停止暂时失败")); await settle();
  check(await runtime.getAttribute("data-state")==="running","Failed stop restores the real prior state instead of claiming it stopped");
  await page.locator(".sw-stop").click(); await page.waitForFunction(()=>document.querySelector("#sw-runtime").dataset.state==="stopping");
  await page.evaluate(()=>window.__activity.releaseStop(null)); await settle();
  check(await runtime.getAttribute("data-state")==="stopping","Stop acknowledgement waits for the terminal event");
  await emit("kz:stopped");
  check(await runtime.getAttribute("data-state")==="stopped","The actual stop interaction settles only on confirmation");
  check(errors.length===0,`No browser errors: ${errors.join("; ")}`);
  await writeFile(path.join(output,"acceptance.json"),JSON.stringify({passed:checks.length,checks,errors},null,2));
  console.log(`Softwire activity PASS: ${checks.length} checks`);
} catch(error) {
  await page.screenshot({path:path.join(output,"failure.png")}); console.error("Passed:",checks); throw error;
} finally {
  const video=page.video(); await page.context().close(); if (video) await video.saveAs(path.join(output,"activity.webm")); await browser.close(); await server.close();
}
