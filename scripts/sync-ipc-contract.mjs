#!/usr/bin/env node
// Cargo owns signature parsing. This explicit developer command publishes its
// output; normal builds never modify checked-in source files.
import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const result = spawnSync("cargo", ["check", "-p", "kanzei-app", "--message-format=json"], {
  cwd: root,
  encoding: "utf8",
  maxBuffer: 64 * 1024 * 1024,
});
if (result.status !== 0) {
  for (const line of result.stdout.split(/\r?\n/).filter(Boolean)) {
    const item = JSON.parse(line);
    if (item.reason === "compiler-message" && item.message.rendered) {
      process.stderr.write(item.message.rendered);
    }
  }
  process.stderr.write(result.stderr || String(result.error));
  process.exit(result.status || 1);
}

const build = result.stdout
  .split(/\r?\n/)
  .filter(Boolean)
  .map((line) => JSON.parse(line))
  .findLast((item) => item.reason === "build-script-executed" && item.package_id.includes("kanzei-app"));
if (!build?.out_dir) {
  throw new Error("Cargo did not report the app contract output directory");
}

const manifest = fs.readFileSync(path.join(build.out_dir, "ipc-commands.json"), "utf8");
const parsed = JSON.parse(manifest);
const commands = Object.fromEntries(
  Object.entries(parsed).map(([name, contract]) => [
    name,
    Object.fromEntries(
      Object.entries(contract.parameters).map(([key, field]) => [key, field.required])
    ),
  ])
);

function rustTypeToTs(raw) {
  const s = raw.replace(/\s+/g, " ").trim();
  const opt = s.match(/^Option\s*<\s*(.+)\s*>$/);
  if (opt) return `${rustTypeToTs(opt[1])} | null`;
  const vec = s.match(/^Vec\s*<\s*(.+)\s*>$/);
  if (vec) return `Array<${rustTypeToTs(vec[1])}>`;
  if (s === "String" || s === "str" || s.endsWith(":: String")) return "string";
  if (s === "bool") return "boolean";
  if (["u8", "u16", "u32", "u64", "i32", "i64", "usize", "f32", "f64"].includes(s)) return "number";
  if (s.includes("HashMap") || s.includes("BTreeMap")) return "Record<string, unknown>";
  return "unknown";
}

const tsArgsLines = Object.entries(parsed).map(([name, contract]) => {
  const entries = Object.entries(contract.parameters);
  if (entries.length === 0) {
    return `  ${JSON.stringify(name)}: Record<string, never>;`;
  }
  const fields = entries
    .map(([param, spec]) => {
      const optional = spec.required ? "" : "?";
      return `${JSON.stringify(param)}${optional}: ${rustTypeToTs(spec.type)}`;
    })
    .join("; ");
  return `  ${JSON.stringify(name)}: { ${fields} };`;
});

const ts = [
  "// Generated by scripts/sync-ipc-contract.mjs from registered Rust signatures.",
  "// Do not edit by hand; run `node scripts/sync-ipc-contract.mjs` after changing Rust commands.",
  "",
  "export interface CommandArgsMap {",
  ...tsArgsLines,
  "}",
  "",
  "export type CommandName = keyof CommandArgsMap;",
  "",
  `export const COMMAND_PARAMETERS: Record<CommandName, Record<string, boolean>> = ${JSON.stringify(commands, null, 2)};`,
  "",
].join("\n");

const targets = [
  ["scripts/ipc-commands.json", manifest],
  ["crates/kanzei-app/web/src/ipc/generated.ts", ts],
];

for (const [relative, data] of targets) {
  const file = path.join(root, relative);
  if (process.argv.includes("--check")) {
    if (
      !fs.existsSync(file) ||
      fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n") !== data.replace(/\r\n/g, "\n")
    ) {
      throw new Error(`${relative} is stale; run node scripts/sync-ipc-contract.mjs`);
    }
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, data);
  }
}

console.log(
  `IPC signatures: ${Object.keys(commands).length} commands; ${process.argv.includes("--check") ? "verified" : "synchronized"}`
);
