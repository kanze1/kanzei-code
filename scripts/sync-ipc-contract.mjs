#!/usr/bin/env node
// Cargo owns signature parsing. This explicit developer command publishes its
// output; normal builds never modify checked-in source files.
import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const result = spawnSync("cargo", ["check", "-p", "kanzei-app", "--message-format=json"], { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
if (result.status !== 0) {
  for (const line of result.stdout.split(/\r?\n/).filter(Boolean)) { const item = JSON.parse(line); if (item.reason === "compiler-message" && item.message.rendered) process.stderr.write(item.message.rendered); }
  process.stderr.write(result.stderr || String(result.error)); process.exit(result.status || 1);
}
const build = result.stdout.split(/\r?\n/).filter(Boolean).map(line => JSON.parse(line)).findLast(item => item.reason === "build-script-executed" && item.package_id.includes("kanzei-app"));
if (!build?.out_dir) throw new Error("Cargo did not report the app contract output directory");
const manifest = fs.readFileSync(path.join(build.out_dir, "ipc-commands.json"), "utf8");
const commands = Object.fromEntries(Object.entries(JSON.parse(manifest)).map(([name, contract]) => [name, Object.fromEntries(Object.entries(contract.parameters).map(([key, field]) => [key, field.required]))]));
const js = `// Generated by scripts/sync-ipc-contract.mjs from registered Rust signatures.\nexport const commandParameters = ${JSON.stringify(commands, null, 2)};\n`;
for (const [relative, data] of [["scripts/ipc-commands.json", manifest], ["crates/kanzei-app/ui/00-command-contract.js", js]]) {
  const file = path.join(root, relative);
  if (process.argv.includes("--check")) { if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== data) throw new Error(`${relative} is stale; run node scripts/sync-ipc-contract.mjs`); }
  else fs.writeFileSync(file, data);
}
console.log(`IPC signatures: ${Object.keys(commands).length} commands; ${process.argv.includes("--check") ? "verified" : "synchronized"}`);
